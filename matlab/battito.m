function y = battito(x)
%BATTITO Curva sintetica tipo elettrocardiogramma, usata come obiettivo.
    t = mod(x, 3.3);
    y = 0.10*sin(1.9*x) ...
      + 1.30*exp(-((t-1.30).^2)/0.05) ...
      - 0.40*exp(-((t-0.85).^2)/0.06) ...
      - 0.45*exp(-((t-1.75).^2)/0.07) ...
      + 0.40*exp(-((t-2.60).^2)/0.35);
end
